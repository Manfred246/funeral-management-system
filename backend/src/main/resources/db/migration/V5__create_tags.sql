CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    CONSTRAINT chk_tags_name CHECK (btrim(name) <> '')
);

-- Сохраняем написание имени, но запрещаем дубликаты, отличающиеся регистром.
CREATE UNIQUE INDEX uq_tags_name_ignore_case ON tags(lower(name));

CREATE TABLE funeral_request_tags (
    funeral_request_id BIGINT NOT NULL REFERENCES funeral_requests(id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags(id) ON DELETE RESTRICT,
    PRIMARY KEY (funeral_request_id, tag_id)
);

CREATE INDEX idx_funeral_request_tags_tag_id ON funeral_request_tags(tag_id);
