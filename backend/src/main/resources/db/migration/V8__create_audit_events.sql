CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(40) NOT NULL CHECK (event_type IN (
        'LOGIN', 'REQUEST_CREATED', 'REQUEST_UPDATED', 'REQUEST_ARCHIVED',
        'REQUEST_RESTORED', 'REQUEST_DELETED', 'USER_CREATED', 'PASSWORD_RESET'
    )),
    entity_type VARCHAR(40) NOT NULL CHECK (entity_type IN ('USER', 'FUNERAL_REQUEST')),
    entity_uuid UUID NOT NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL,
    description VARCHAR(255) NOT NULL,
    correlation_id VARCHAR(64) NOT NULL
);

CREATE INDEX idx_audit_events_created_at ON audit_events(created_at DESC, id DESC);
CREATE INDEX idx_audit_events_user_id ON audit_events(user_id);
